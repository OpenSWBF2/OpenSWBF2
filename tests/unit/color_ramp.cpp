unsigned int Fnv(const unsigned short awRamp[256])
{
    unsigned int uiHash = 2166136261u;
    for (int i = 0; i < 256; i++)
    {
        uiHash = (uiHash ^ awRamp[i]) * 16777619u;
    }
    return uiHash;
}

void CheckRamp(float fContrast, float fBrightness, float fGamma,
               const unsigned short awExpected[256], unsigned int uiFnv,
               unsigned short awOut[256])
{
    const float afLevel[3] = {fContrast, fBrightness, fGamma};
    ColorRamp::Build(afLevel, awOut);
    int iMismatch = -1;
    for (int i = 0; i < 256; i++)
    {
        if (awOut[i] != awExpected[i])
        {
            iMismatch = i;
            break;
        }
    }
    CHECK(iMismatch == -1);
    CHECK(Fnv(awOut) == uiFnv);
}

int CheckNegativeBaseIsZero(float fContrast, float fBrightness, const unsigned short awRamp[256])
{
    const float fScale = fContrast * 1.8f + 0.1f;
    const float fOffset = fBrightness * 1.5f - 0.75f;
    int iCount = 0;
    for (int i = 0; i < 256; i++)
    {
        const float fBase = ((float)i * (1.0f / 255.0f) - 0.5f + fOffset) * fScale + 0.5f;
        if (fBase < 0.0f)
        {
            iCount++;
            CHECK(awRamp[i] == 0);
        }
    }
    return iCount;
}

int CountZero(const unsigned short awRamp[256])
{
    int iCount = 0;
    for (int i = 0; i < 256; i++)
    {
        if (awRamp[i] == 0)
        {
            iCount++;
        }
    }
    return iCount;
}

